// VARVEL — target defense fingerprinting + per-target stealth calibration.
//
// RedAmon NAMES this exact problem in its whitepaper — "--max-rate 50 against this
// hardened target but --max-rate 200 against a different less-monitored one" — then
// PUNTS it to the LLM ("context-sensitive judgment that hard limits would over-
// constrain"). VARVEL makes it a MEASURED decision: passively fingerprint the target's
// defensive stack (WAF/CDN vendor, rate-limit signals, bot-challenge, security-header
// maturity) from responses we already receive, then auto-calibrate the ENFORCED stealth
// profile + noise budget to that target. Adaptive stealth, not a static prompt.
//
// DISCOVERY + CALIBRATION only. It reads what the target volunteers and chooses to be
// appropriately quiet on an AUTHORIZED engagement — it does NOT defeat, bypass, or evade
// any control; every request is still recorded in the Enclave's tamper-evident audit.

